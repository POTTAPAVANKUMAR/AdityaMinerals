        // Excel Content Methods
        private void AddInvoiceContentToExcel(ExcelWorksheet worksheet, InvoiceReportData data, int startRow)
        {
            int row = startRow;

            // Invoice header
            worksheet.Cells[row, 1].Value = "Invoice No:";
            worksheet.Cells[row, 2].Value = data.InvoiceHeader?.InvoiceNo;
            row++;

            worksheet.Cells[row, 1].Value = "Date:";
            worksheet.Cells[row, 2].Value = data.InvoiceHeader?.DateOfIssue;
            row++;

            worksheet.Cells[row, 1].Value = "Customer:";
            worksheet.Cells[row, 2].Value = data.InvoiceHeader?.BP_Name_VC;
            row += 2;

            // Headers
            worksheet.Cells[row, 1].Value = "Product";
            worksheet.Cells[row, 2].Value = "Quantity";
            worksheet.Cells[row, 3].Value = "Rate";
            worksheet.Cells[row, 4].Value = "Amount";
            worksheet.Cells[row, 5].Value = "Net Amount";

            // Style headers
            using (var range = worksheet.Cells[row, 1, row, 5])
            {
                range.Style.Font.Bold = true;
                range.Style.Fill.PatternType = ExcelFillStyle.Solid;
                range.Style.Fill.BackgroundColor.SetColor(System.Drawing.Color.LightGray);
            }

            row++;

            // Data
            foreach (var item in data.InvoiceItems ?? new List<AdityaMinerals.EntityModels.ADM_L_BILLINGPART2>())
            {
                worksheet.Cells[row, 1].Value = item.ProductionDescription_VC;
                worksheet.Cells[row, 2].Value = item.QTY;
                worksheet.Cells[row, 3].Value = item.Rate;
                worksheet.Cells[row, 4].Value = item.Amount;
                worksheet.Cells[row, 5].Value = item.ValueofSupply;
                row++;
            }

            // Totals
            row++;
            worksheet.Cells[row, 4].Value = "Total Amount:";
            worksheet.Cells[row, 5].Value = data.TotalAmount;
            worksheet.Cells[row, 4, row, 5].Style.Font.Bold = true;
        }

