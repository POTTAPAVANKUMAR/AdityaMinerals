        public byte[] GenerateReport(EnhancedReportModel reportModel, ReportFormat format)
        {
            switch (format)
            {
                case ReportFormat.PDF:
                    return GeneratePdfReport(reportModel);
                case ReportFormat.Excel:
                    return GenerateExcelReport(reportModel);
                case ReportFormat.CSV:
                    return GenerateCsvReport(reportModel);
                case ReportFormat.JSON:
                    return GenerateJsonReport(reportModel);
                default:
                    throw new ArgumentException("Unsupported report format");
            }
        }

        private byte[] GeneratePdfReport(EnhancedReportModel reportModel)
        {
            using (var memoryStream = new MemoryStream())
            {
                var document = new Document(PageSize.A4, 25, 25, 30, 30);
                var writer = PdfWriter.GetInstance(document, memoryStream);
                
                document.Open();

                // Add title
                var titleFont = FontFactory.GetFont(FontFactory.HELVETICA_BOLD, 18, BaseColor.BLACK);
                var title = new Paragraph(reportModel.ReportTitle, titleFont)
                {
                    Alignment = Element.ALIGN_CENTER,
                    SpacingAfter = 20
                };
                document.Add(title);

                // Add metadata
                var metadataFont = FontFactory.GetFont(FontFactory.HELVETICA, 10, BaseColor.GRAY);
                var metadata = new Paragraph($"Generated on: {reportModel.GeneratedDate:yyyy-MM-dd HH:mm:ss} by {reportModel.GeneratedBy}", metadataFont)
                {
                    Alignment = Element.ALIGN_RIGHT,
                    SpacingAfter = 20
                };
                document.Add(metadata);

                // Add content based on report type
                switch (reportModel.ReportType)
                {
                    case ReportType.Invoice:
                        AddInvoiceContentToPdf(document, (InvoiceReportData)reportModel.Data);
                        break;
                    case ReportType.SalesReport:
                        AddSalesContentToPdf(document, (SalesReportData)reportModel.Data);
                        break;
                    case ReportType.ProductSummary:
                        AddProductContentToPdf(document, (ProductReportData)reportModel.Data);
                        break;
                    case ReportType.CustomerReport:
                        AddCustomerContentToPdf(document, (CustomerReportData)reportModel.Data);
                        break;
                }

                document.Close();
                return memoryStream.ToArray();
            }
        }

        private byte[] GenerateExcelReport(EnhancedReportModel reportModel)
        {
            using (var package = new ExcelPackage())
            {
                var worksheet = package.Workbook.Worksheets.Add(reportModel.ReportTitle);

                // Add header
                worksheet.Cells[1, 1].Value = reportModel.ReportTitle;
                worksheet.Cells[1, 1].Style.Font.Size = 16;
                worksheet.Cells[1, 1].Style.Font.Bold = true;

                worksheet.Cells[2, 1].Value = $"Generated on: {reportModel.GeneratedDate:yyyy-MM-dd HH:mm:ss}";
                worksheet.Cells[3, 1].Value = $"Generated by: {reportModel.GeneratedBy}";

                int startRow = 5;

                // Add content based on report type
                switch (reportModel.ReportType)
                {
                    case ReportType.Invoice:
                        AddInvoiceContentToExcel(worksheet, (InvoiceReportData)reportModel.Data, startRow);
                        break;
                    case ReportType.SalesReport:
                        AddSalesContentToExcel(worksheet, (SalesReportData)reportModel.Data, startRow);
                        break;
                    case ReportType.ProductSummary:
                        AddProductContentToExcel(worksheet, (ProductReportData)reportModel.Data, startRow);
                        break;
                    case ReportType.CustomerReport:
                        AddCustomerContentToExcel(worksheet, (CustomerReportData)reportModel.Data, startRow);
                        break;
                }

                // Auto-fit columns
                worksheet.Cells.AutoFitColumns();

                return package.GetAsByteArray();
            }
        }

        private byte[] GenerateCsvReport(EnhancedReportModel reportModel)
        {
            using (var memoryStream = new MemoryStream())
            using (var writer = new StreamWriter(memoryStream))
            using (var csv = new CsvWriter(writer, CultureInfo.InvariantCulture))
            {
                // Write header information
                csv.WriteField("Report Title");
                csv.WriteField(reportModel.ReportTitle);
                csv.NextRecord();

                csv.WriteField("Generated Date");
                csv.WriteField(reportModel.GeneratedDate.ToString("yyyy-MM-dd HH:mm:ss"));
                csv.NextRecord();

                csv.WriteField("Generated By");
                csv.WriteField(reportModel.GeneratedBy);
                csv.NextRecord();
                csv.NextRecord(); // Empty line

                // Add content based on report type
                switch (reportModel.ReportType)
                {
                    case ReportType.SalesReport:
                        AddSalesContentToCsv(csv, (SalesReportData)reportModel.Data);
                        break;
                    case ReportType.ProductSummary:
                        AddProductContentToCsv(csv, (ProductReportData)reportModel.Data);
                        break;
                    case ReportType.CustomerReport:
                        AddCustomerContentToCsv(csv, (CustomerReportData)reportModel.Data);
                        break;
                    default:
                        csv.WriteField("Data export not supported for this report type in CSV format");
                        csv.NextRecord();
                        break;
                }

                writer.Flush();
                return memoryStream.ToArray();
            }
        }

        private byte[] GenerateJsonReport(EnhancedReportModel reportModel)
        {
            var json = JsonConvert.SerializeObject(reportModel, Formatting.Indented);
            return Encoding.UTF8.GetBytes(json);
        }

        // PDF Content Methods
        private void AddInvoiceContentToPdf(Document document, InvoiceReportData data)
        {
            var headerFont = FontFactory.GetFont(FontFactory.HELVETICA_BOLD, 12);
            var normalFont = FontFactory.GetFont(FontFactory.HELVETICA, 10);

            // Invoice header info
            document.Add(new Paragraph($"Invoice No: {data.InvoiceHeader?.InvoiceNo}", headerFont));
            document.Add(new Paragraph($"Date: {data.InvoiceHeader?.DateOfIssue:yyyy-MM-dd}", normalFont));
            document.Add(new Paragraph($"Customer: {data.InvoiceHeader?.BP_Name_VC}", normalFont));
            document.Add(new Paragraph(" ")); // Space

            // Invoice items table
            var table = new PdfPTable(5);
            table.WidthPercentage = 100;

            // Headers
            table.AddCell(new PdfPCell(new Phrase("Product", headerFont)));
            table.AddCell(new PdfPCell(new Phrase("Quantity", headerFont)));
            table.AddCell(new PdfPCell(new Phrase("Rate", headerFont)));
            table.AddCell(new PdfPCell(new Phrase("Amount", headerFont)));
            table.AddCell(new PdfPCell(new Phrase("Net Amount", headerFont)));

            // Data rows
            foreach (var item in data.InvoiceItems ?? new List<AdityaMinerals.EntityModels.ADM_L_BILLINGPART2>())
            {
                table.AddCell(new PdfPCell(new Phrase(item.ProductionDescription_VC ?? "", normalFont)));
                table.AddCell(new PdfPCell(new Phrase(item.QTY?.ToString() ?? "0", normalFont)));
                table.AddCell(new PdfPCell(new Phrase(item.Rate?.ToString("C") ?? "0", normalFont)));
                table.AddCell(new PdfPCell(new Phrase(item.Amount?.ToString("C") ?? "0", normalFont)));
                table.AddCell(new PdfPCell(new Phrase(item.ValueofSupply?.ToString("C") ?? "0", normalFont)));
            }

            document.Add(table);

            // Totals
            document.Add(new Paragraph(" "));
            document.Add(new Paragraph($"Total Amount: {data.TotalAmount:C}", headerFont));
            document.Add(new Paragraph($"Total Discount: {data.TotalDiscount:C}", headerFont));
            document.Add(new Paragraph($"Net Amount: {data.NetAmount:C}", headerFont));
        }

        private void AddSalesContentToPdf(Document document, SalesReportData data)
        {
