            var normalFont = FontFactory.GetFont(FontFactory.HELVETICA, 10);

            // Summary
            document.Add(new Paragraph($"Report Period: {data.ReportPeriodStart:yyyy-MM-dd} to {data.ReportPeriodEnd:yyyy-MM-dd}", headerFont));
            document.Add(new Paragraph($"Total Sales: {data.TotalSales:C}", headerFont));
            document.Add(new Paragraph($"Total Invoices: {data.TotalInvoices}", headerFont));
            document.Add(new Paragraph(" "));

            // Sales items table
            var table = new PdfPTable(5);
            table.WidthPercentage = 100;

            table.AddCell(new PdfPCell(new Phrase("Invoice No", headerFont)));
            table.AddCell(new PdfPCell(new Phrase("Date", headerFont)));
            table.AddCell(new PdfPCell(new Phrase("Customer", headerFont)));
            table.AddCell(new PdfPCell(new Phrase("Amount", headerFont)));
            table.AddCell(new PdfPCell(new Phrase("Net Amount", headerFont)));

            foreach (var item in data.SalesItems ?? new List<SalesSummaryItem>())
            {
                table.AddCell(new PdfPCell(new Phrase(item.InvoiceNo.ToString(), normalFont)));
                table.AddCell(new PdfPCell(new Phrase(item.InvoiceDate.ToString("yyyy-MM-dd"), normalFont)));
                table.AddCell(new PdfPCell(new Phrase(item.CustomerName ?? "", normalFont)));
                table.AddCell(new PdfPCell(new Phrase(item.InvoiceAmount.ToString("C"), normalFont)));
                table.AddCell(new PdfPCell(new Phrase(item.NetAmount.ToString("C"), normalFont)));
            }

            document.Add(table);
        }

